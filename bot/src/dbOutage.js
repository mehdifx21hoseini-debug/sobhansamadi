// وقتی دیتابیس جواب نمی‌دهد، ربات باید حرف بزند - نه اینکه ساکت شود.
//
// چرا این فایل هست: روزی که سقفِ روزانه‌ی خواندنِ D1 پر شد، ورکر کاملاً
// سالم بود، وبهوک ثبت بود، تلگرام پیام‌ها را تحویل می‌داد و ورکر
// قبولشان می‌کرد - ولی هر کوئری خطا می‌داد و هر هندلر بی‌صدا می‌افتاد.
// از بیرون، ربات فقط «کار نمی‌کرد». نه پیامی، نه خطایی، نه نشانه‌ای.
// یازده هزار نفر دکمه می‌زدند و هیچ اتفاقی نمی‌افتاد.
//
// آن سکوت بدترین بخشِ ماجرا بود، نه خودِ قطعی. قطعی چند ساعت طول کشید؛
// فهمیدنِ اینکه چه شده، همان‌قدر.
//
// پس دو کار اینجا انجام می‌شود، و هر دو عمداً بدونِ دیتابیس کار می‌کنند:
//
//   ۱. کاربر یک پیامِ روشن می‌گیرد به‌جای سکوت.
//   ۲. مدیر یک بار خبردار می‌شود - نه هزار بار.

import { OWNER_ID } from "./owner.js";

// خطاهایی که یعنی «دیتابیس در دسترس نیست»، نه «کوئری غلط بود».
//
// پیامِ سقف را خودِ کلادفلر می‌سازد و متنش ثابت است. بقیه حالت‌های
// شناخته‌شده‌ی قطعیِ زیرساخت‌اند. هر چیزِ دیگری عمداً اینجا نمی‌افتد:
// یک باگِ SQL نباید پشتِ پیامِ «شلوغی» پنهان شود.
const OUTAGE_PATTERNS = [
  /exceeded .*(daily|free tier).*(row|read|write|limit)/i,
  /D1_ERROR.*(limit|exceeded)/i,
  /Network connection lost/i,
  /storage (operation|backend) (failed|error)/i,
  /Internal error in D1/i,
];

export function isDbOutage(err) {
  const msg = String((err && err.message) || err || "");
  return OUTAGE_PATTERNS.some((re) => re.test(msg));
}

// متنی که کاربر می‌بیند.
//
// عمداً از «سقف» و «دیتابیس» و «کلادفلر» حرفی نمی‌زند: برای کاربر
// بی‌معنی است و فقط نگرانش می‌کند. آنچه لازم دارد این است که بداند
// خراب‌کاری از سمت او نیست و کِی برگردد.
export const USER_TEXT =
  "⚠️ ربات موقتاً در دسترس نیست\n\n" +
  "یک مشکل فنی گذرا پیش آمده و در حال رفعش هستیم.\n\n" +
  "چند دقیقه‌ی دیگر دوباره امتحان کنید — اطلاعات شما جای خودش امن است.";

// ─── خبر دادن به مدیر، یک بار ───────────────────────────────────────
//
// در حافظه‌ی همان ایزوله، نه در دیتابیس. دلیلش روشن است: دیتابیسی که
// خراب است، جای نگه داشتنِ «خبر دادم یا نه» نیست.
//
// یعنی اگر کلادفلر چند ایزوله بالا بیاورد، ممکن است چند پیام برود. این
// پذیرفته شده است: چند پیامِ تکراری از سکوتِ کامل خیلی بهتر است، و
// فاصله‌ی یک‌ساعته جلوی سیل را می‌گیرد.
const NOTIFY_EVERY_MS = 60 * 60 * 1000;
let lastNotifiedAt = 0;

/**
 * به مدیر خبر می‌دهد که دیتابیس خوابیده.
 *
 * مستقیم با fetch به تلگرام می‌رود، نه از مسیرِ grammy: هر چه کمتر به
 * کدی که ممکن است خودش به دیتابیس بزند وابسته باشد، بهتر.
 */
export async function notifyOwner(env, err, now = Date.now()) {
  // «هرگز خبر نداده‌ام» جدا بررسی می‌شود، نه با حساب کردنِ فاصله از صفر.
  // با Date.now()ِ واقعی هر دو یک نتیجه می‌دهند و همین خطا را پنهان
  // می‌کرد؛ ولی منطقِ درست این است که اولین خبر هرگز عقب نیفتد.
  if (lastNotifiedAt !== 0 && now - lastNotifiedAt < NOTIFY_EVERY_MS) {
    return { skipped: "تکراری" };
  }
  // OWNER_ID یک ثابت در کد است، نه یک ردیف در دیتابیس - و همین اینجا
  // اهمیت دارد: مقصدِ این پیام نباید از جایی خوانده شود که خراب است.
  const chatId = OWNER_ID;
  if (!chatId || !env || !env.BOT_TOKEN) return { skipped: "تنظیم نشده" };

  lastNotifiedAt = now;

  const text =
    "🚨 دیتابیس ربات جواب نمی‌دهد\n\n" +
    "ورکر بالاست ولی هر کوئری خطا می‌دهد، پس ربات عملاً برای کاربران " +
    "ساکت است.\n\n" +
    "خطا:\n" +
    String((err && err.message) || err || "").slice(0, 300);

  try {
    await fetch("https://api.telegram.org/bot" + env.BOT_TOKEN + "/sendMessage", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      signal: AbortSignal.timeout(10000),
      body: JSON.stringify({ chat_id: chatId, text }),
    });
    return { ok: true };
  } catch {
    // خبر دادن که خودش شکست بخورد، جایی برای گزارش ندارد.
    return { ok: false };
  }
}

/** فقط برای تست. */
export function resetNotifier() {
  lastNotifiedAt = 0;
}
