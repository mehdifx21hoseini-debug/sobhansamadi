// سطح‌های اهمیت، و اینکه کاربر کدام‌هایشان را هشدار بگیرد.
//
// ─── چرا سه سطح و نه چهار ─────────────────────────────────────────
//
// فیدِ ForexFactory در فیلدِ impact فقط چهار مقدار دارد: High، Medium،
// Low، و Holiday. سه‌تای اول همین سه سطح‌اند؛ Holiday اصلاً رویداد
// نیست و جدول و بخشِ خودش را دارد، پس همان موقعِ دریافت کنار گذاشته
// می‌شود (ingest.js).
//
// روی سایت رنگ‌ها قرمز و نارنجی و زردند - و همین باعثِ سوءتفاهم است:
// «مهم» در حرفِ روزمره یعنی نارنجی، ولی در دادهٔ فید medium است. برای
// همین در برچسب‌ها هر دو آمده، هم نامِ فارسی هم رنگِ فارکس‌فکتوری.
//
// ─── چه چیزی عوض شد ───────────────────────────────────────────────
//
// پیش از این یک کلیدِ دوحالته بود: show_low_importance. نامش یک چیز
// می‌گفت و کارش چیزِ دیگری بود - خاموش یعنی «فقط خیلی مهم»، روشن یعنی
// «خیلی مهم + مهم». خبرهای کم‌اهمیت هیچ‌وقت نمی‌رفتند، با هیچ حالتی.
//
// و متنِ تنظیماتِ مینی‌اپ می‌نوشت «پیش‌فرض: فقط مهم و خیلی مهم»، که
// دقیقاً همان چیزی نبود که اتفاق می‌افتاد. نتیجه‌اش یک شکایتِ واقعی
// بود: سخنرانیِ ترامپ که در فید نارنجی (medium) بود، برای هیچ‌کس
// هشدار نشد.
//
// حالا کاربر هر سه را جدا انتخاب می‌کند و پیش‌فرض همان چیزی است که آن
// متن از اول وعده داده بود.

export const ALERT_LEVELS = [
  { key: "high", fa: "خیلی مهم", emoji: "🔴", color: "قرمز" },
  { key: "medium", fa: "مهم", emoji: "🟠", color: "نارنجی" },
  { key: "low", fa: "کم‌اهمیت", emoji: "🟡", color: "زرد" },
];

const ORDER = ALERT_LEVELS.map((l) => l.key);
const VALID = new Set(ORDER);

/**
 * پیش‌فرض: خیلی مهم و مهم.
 *
 * «مهم» عمداً داخل است. تا دیروز بیرون بود و همان چیزی بود که
 * سخنرانی‌های نارنجی را بی‌صدا می‌انداخت.
 */
export const DEFAULT_LEVELS = ["high", "medium"];

export function levelLabel(key) {
  const l = ALERT_LEVELS.find((x) => x.key === key);
  return l ? l.fa : key;
}

/**
 * رشته‌ی ذخیره‌شده → فهرست.
 *
 * خالی یا نامعتبر یعنی پیش‌فرض، نه «هیچ»: کاربری که هیچ سطحی نداشته
 * باشد هیچ هشداری نمی‌گیرد و فکر می‌کند ربات خراب است - در حالی که
 * برای «هیچ هشداری نمی‌خواهم» کلیدِ خودِ اشتراک هست.
 */
export function parseLevels(raw) {
  const list = String(raw || "")
    .split(",")
    .map((s) => s.trim().toLowerCase())
    .filter((s) => VALID.has(s));
  const uniq = [...new Set(list)];
  return uniq.length ? ORDER.filter((k) => uniq.includes(k)) : [...DEFAULT_LEVELS];
}

export function serializeLevels(list) {
  const clean = (Array.isArray(list) ? list : [])
    .map((s) => String(s || "").trim().toLowerCase())
    .filter((s) => VALID.has(s));
  const uniq = [...new Set(clean)];
  return (uniq.length ? ORDER.filter((k) => uniq.includes(k)) : DEFAULT_LEVELS).join(",");
}

/** روشن/خاموش کردنِ یک سطح، با نگه داشتنِ ترتیبِ اصلی. */
export function toggleLevel(current, key) {
  const k = String(key || "").trim().toLowerCase();
  if (!VALID.has(k)) return [...current];
  const set = new Set(current);
  if (set.has(k)) set.delete(k);
  else set.add(k);
  // آخرین سطح خاموش نمی‌شود.
  //
  // بدونِ این، کاربر می‌توانست مشترک بماند و هیچ‌وقت هیچ هشداری نگیرد -
  // حالتی که از بیرون با «ربات خراب است» یکی به نظر می‌رسد. برای
  // نخواستنِ هشدار، کلیدِ خودِ اشتراک هست.
  if (set.size === 0) return [...current];
  return ORDER.filter((x) => set.has(x));
}

/**
 * برای ردیف‌هایی که پیش از این ستون ساخته شده‌اند.
 *
 * کلیدِ قدیمی دو حالت داشت - «فقط خیلی مهم» و «خیلی مهم + مهم» - و هر
 * دو به همان پیش‌فرضِ تازه می‌رسند. یعنی هیچ‌کس هشداری را از دست
 * نمی‌دهد؛ کسانی که کلیدشان خاموش بود از این به بعد «مهم» را هم
 * می‌گیرند، که دقیقاً خواستِ آکادمی است.
 *
 * «کم‌اهمیت» به هیچ‌کس تحمیل نمی‌شود: تا دیروز برای هیچ‌کس نمی‌رفت،
 * پس روشن کردنش برای همه یعنی یک موجِ هشدارِ ناخواسته.
 */
export function levelsFromLegacy() {
  return [...DEFAULT_LEVELS];
}
