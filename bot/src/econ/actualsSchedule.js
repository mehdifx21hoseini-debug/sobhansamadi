// چه وقت باید خواندنِ عددهای واقعی را صدا زد.
//
// ─── مسئله ─────────────────────────────────────────────────────────
//
// عددِ «واقعی» در فید عمومیِ تقویم نیست - آنجا فقط پیش‌بینی و قبلی
// هست. پس یک کارِ جدا با مرورگرِ واقعی صفحه‌ی ForexFactory را می‌خواند
// و نتیجه را به /econ/ingest می‌فرستد.
//
// آن کار زمان‌بندیِ خودش را داشت: دقیقه‌ی ۵ و ۳۵ هر ساعت، در ساعاتِ
// انتشارِ آمریکا - یعنی روزی ۲۲ بار، و آن ۵ و ۳۵ عمداً پنج دقیقه بعد
// از ساعت‌های معمولِ انتشار (۸:۳۰ و ۱۰:۰۰ نیویورک) بود.
//
// ولی زمان‌بندِ گیت‌هاب «بهترین تلاش» است، نه تضمین. تاریخچه‌ی دو هفته
// نشان داد عملاً روزی ۴ بار اجرا می‌شود، با ۰ تا ۵۹ دقیقه تأخیر - یعنی
// حدود ۸۲٪ اجراها اصلاً انجام نمی‌شود. نتیجه‌اش برای کاربر این بود که
// ستونِ «واقعی» دو تا سه ساعت بعد از انتشار پر می‌شد، نه پنج دقیقه.
//
// ─── راه‌حل، که یک بار جواب داده ───────────────────────────────────
//
// همین اتفاق برای خلاصه‌ی صبح افتاد و سه روز پیاپی چهار ساعت دیر رفت.
// حلش این بود که کرانِ خودِ کلادفلر - که سرِ وقت اجرا می‌شود - ورک‌فلو را
// صدا بزند. همان الگو اینجا هم به کار می‌رود.
//
// زمان‌بندیِ خودِ گیت‌هاب روی ورک‌فلو می‌ماند، به‌عنوان تورِ ایمنی: اگر
// روزی کرانِ کلادفلر یا توکنِ دیسپچ از کار بیفتد، عددها دیر می‌رسند
// ولی می‌رسند. اجرای تکراری ضرری ندارد چون ثبت idempotent است.

// پنجره‌ی انتشار، به UTC.
//
// ۱۲ تا ۲۲ یعنی ۸:۰۵ تا ۱۸:۳۵ نیویورک در زمستان و یک ساعت زودتر در
// تابستان - بازه‌ای که داده‌های آمریکا واقعاً منتشر می‌شوند. بیرون از
// آن، صفحه چیزِ تازه‌ای ندارد و خواندنش فقط هزینه است.
const FIRST_HOUR = 12;
const LAST_HOUR = 22;

// دقیقه‌ی ۵ و ۳۵: پنج دقیقه بعد از دو زمانِ معمولِ انتشار.
const MINUTES = [5, 35];

/**
 * آیا این تیکِ کران باید عددها را بخواند؟
 *
 * ورودی همان لحظه‌ای است که کران *برایش* برنامه‌ریزی شده، نه لحظه‌ی
 * اجرا. اگر کلادفلر چند ثانیه دیر صدا بزند، دقیقه‌ی محاسبه‌شده نباید
 * جابه‌جا شود - وگرنه همان تیک از قلم می‌افتد و ساعتی یک بار می‌شود.
 *
 * @param {Date} scheduled
 */
export function isActualsSlot(scheduled) {
  const d = scheduled instanceof Date ? scheduled : new Date(scheduled);
  if (isNaN(d.getTime())) return false;

  // شنبه و یکشنبه بازار تعطیل است و داده‌ای منتشر نمی‌شود.
  const day = d.getUTCDay();
  if (day === 0 || day === 6) return false;

  const hour = d.getUTCHours();
  if (hour < FIRST_HOUR || hour > LAST_HOUR) return false;

  return MINUTES.indexOf(d.getUTCMinutes()) !== -1;
}

/** فقط برای تست و گزارش. */
export const ACTUALS_WINDOW = { FIRST_HOUR, LAST_HOUR, MINUTES };
