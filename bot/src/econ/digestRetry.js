// دورِ دومِ خلاصه‌ی صبح.
//
// چرا لازم شد: ۲۸ اکتبر اجرای ۷:۳۰ فقط برای ۵٬۷۴۴ نفر رفت و شاردها زودتر
// از موعد «تمام شد» گفتند. بقیه (حدود ۱۱ هزار نفر) تا ۱۳:۴۳ تهران منتظر
// ماندند، چون تنها چیزی که کار را کامل کرد زمان‌بندِ خودِ گیت‌هاب بود -
// که هر روز چند ساعت دیر می‌آید.
//
// این دور ۹:۰۰ تهران (۰۵:۳۰ UTC) همان ورک‌فلو را دوباره صدا می‌زند. بی‌خطر
// است: دفترِ ارسال جلوی پیامِ دوباره را می‌گیرد، و اگر اجرای صبح کامل
// بوده باشد این دور در چند ثانیه تمام می‌شود.
//
// روی کرانِ پنج‌دقیقه‌ای سوار است و کران تازه نمی‌سازد: پلنِ رایگانِ
// کلادفلر پنج کران می‌دهد و پنج‌تایش الان پر است.

const HOUR = 5;
const MINUTE = 30;

/**
 * آیا این تیکِ کران باید دورِ دومِ خلاصه را شروع کند؟
 *
 * ورودی همان لحظه‌ای است که کران *برایش* برنامه‌ریزی شده، نه لحظه‌ی
 * اجرا، تا چند ثانیه تأخیر تیک را نیندازد.
 *
 * هر روز، حتی آخر هفته: خلاصه‌ی آخر هفته هم می‌رود.
 *
 * @param {Date|number} scheduled
 */
export function isDigestRetrySlot(scheduled) {
  const d = scheduled instanceof Date ? scheduled : new Date(scheduled);
  if (isNaN(d.getTime())) return false;
  return d.getUTCHours() === HOUR && d.getUTCMinutes() === MINUTE;
}
