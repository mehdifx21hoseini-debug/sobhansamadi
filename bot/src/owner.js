// آیدی مدیر آکادمی، در یک جا.
//
// این عدد پیش‌تر در سه فایل تکرار شده بود (دروازه‌ی عضویت، تشخیص، و
// دریافت کانال). تکرارِ یک ثابت یعنی روزی که عوض شود، یکی از سه‌تا
// جا می‌ماند و آن یکی مسیر بی‌صدا برای مدیر بسته می‌شود.
export const OWNER_ID = "6923823275";

export function isOwner(ctx) {
  return !!ctx.from && String(ctx.from.id) === OWNER_ID;
}
