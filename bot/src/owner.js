// بدون @ و با حروف کوچک؛ مقایسه بی‌توجه به بزرگی و کوچکی حروف است.
export const OWNER_USERNAMES = [];

// اولین آیدی عددی: مقصد پیام‌های خودکار ربات به مدیر. نام کاربری
// اینجا به کار نمی‌آید، چون برای فرستادن پیام باید عدد داشت.
export const OWNER_ID = OWNER_IDS[0];

export function isOwner(ctx) {
  const from = ctx && ctx.from;
  if (!from) return false;
  if (OWNER_IDS.includes(String(from.id))) return true;
  const username = String(from.username || "").toLowerCase();
  return !!username && OWNER_USERNAMES.includes(username);
}
