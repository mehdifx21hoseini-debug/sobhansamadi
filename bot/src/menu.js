// آیدی ایموجی‌های پرمیوم، از همان نود Send Main Menu.
const ICON = {
  ECON_CALENDAR: "5274055917766202507",
  LIVE_TRADE: "5197503331215361533",
  CONSULT: "5195033767969839232",
};

function btn(text, style, iconId) {
  const b = { text, style };
  if (iconId) b.icon_custom_emoji_id = iconId;
  return b;
}

// چیدمان: هر ردیف یک منطق دارد، نه جفت‌های تصادفی.
//
//   ۱ - چیزی که روزانه برمی‌گردانَد، کنار درِ ورودی تازه‌واردها
//   ۲ - جفت روانشناسی: کتاب و ویس، یک خانواده‌ی محتوایی
//   ۳ - ابزار و ویدیو
//   ۴ - تنها مسیری که مستقیم درآمد می‌سازد: تنها، تمام‌عرض، سبز
//   ۵ - جایی که کاربر برای کمک می‌رود
//   ۶ - اطلاعات، که کمترین مراجعه را دارد و پایین‌ترین جاست
//
// در کیبورد راست‌به‌چپ، دکمه‌ی اولِ هر ردیف سمت راست می‌نشیند و اول
// خوانده می‌شود؛ پس در هر جفت، مهم‌تری اول آمده.
export function mainMenuKeyboard() {
  return {
    keyboard: [
      [
        btn(MENU_LABELS.ECON_CALENDAR, "primary", ICON.ECON_CALENDAR),
        btn(MENU_LABELS.FREE_COURSES, "primary"),
      ],
      [btn(MENU_LABELS.LIBRARY, "primary"), btn(MENU_LABELS.PSY_VOICES, "primary")],
      [
        btn(MENU_LABELS.EXPERT, "primary"),
        btn(MENU_LABELS.LIVE_TRADE, "primary", ICON.LIVE_TRADE),
      ],
      [btn(MENU_LABELS.CONSULT, "success", ICON.CONSULT)],
      // سه دکمه در یک ردیف چون هر سه برچسب کوتاه‌اند - و این‌طور کیبورد
      // یک ردیف کمتر می‌شود، یعنی یک ردیف بیشتر از خودِ گفتگو دیده می‌شود.
      [
        btn(MENU_LABELS.TRUSTED_BROKER, "primary"),
        btn(MENU_LABELS.SUPPORT, "primary"),
        btn(MENU_LABELS.ABOUT_US, "primary"),
      ],
    ],
    resize_keyboard: true,
    one_time_keyboard: false,
  };
}

// کیبورد تلگرام سمت کاربر کش می‌شود و تا وقتی همه یک‌بار /start نزده‌اند،
// متن‌های نسخه‌های قبلی هنوز فرستاده می‌شوند. هر کدام باید شناخته شود،
// وگرنه ضربه‌شان بی‌جواب می‌ماند.
//
// اینجا سه نسل کنار هم‌اند: نسخه‌ی اول (با ایموجی روی تقویم و ثبت‌نام)،
// نسخه‌ی زیرمنودار، و ایموجی‌های آزمایشی که یک روز عوض شدند.
const LEGACY_LABELS = {
  "📅 تقویم اقتصادی": "ECON_CALENDAR",
  "🚀 شرکت در مجموعه آموزشی پیشرفته": "CONSULT",
  "📈 ویدیوهای لایو ترید": "LIVE_TRADE",
  "💜 درباره آکادمی": "ABOUT",
  "🏛 درباره آکادمی": "ABOUT",
  "📞 تماس با ما": "CONTACT",

  // دکمه‌های نسخه‌ی زیرمنودار. زیرمنوها هنوز کار می‌کنند تا کاربری که
  // کیبورد آن نسخه را دارد به بن‌بست نخورد.
  "🎓 آموزش‌ها": "LEARN",
  "🧰 ابزارها": "TOOLS",
};

// تنها جایی که متن ورودی به کنش منو نگاشته می‌شود. هم متن فعلی و هم
// متن‌های قدیمی را می‌پذیرد و اگر هیچ‌کدام نبود null برمی‌گرداند.
export function resolveMenuAction(text) {
  for (const [key, label] of Object.entries(MENU_LABELS)) {
    if (label === text) return key;
  }
  return LEGACY_LABELS[text] || null;
}
