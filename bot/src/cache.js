// کشِ کوتاه‌مدت داخل ورکر.
//
// چرا لازم شد: روزی که سقف روزانه‌ی خواندنِ D1 پر شد و ربات برای یازده
// هزار نفر ساکت ماند، دو الگو پیدا شد که هر دو یک ریشه داشتند - خواندنِ
// دوباره‌ی دیتای یکسان.
//
//   readEvents() کلِ جدولِ تقویم را بی‌هیچ WHERE می‌خواند، و هر بار که
//   کسی «اخبار امروز» را می‌زند دوباره اجرا می‌شود. یازده هزار کاربر
//   یعنی یازده هزار بار خواندنِ همان چند صد ردیف - در حالی که داده‌اش
//   ساعتی یک بار عوض می‌شود.
//
// ورکر بین درخواست‌ها زنده می‌ماند، پس یک Map ساده در حافظه‌ی همان
// ایزوله این را می‌گیرد. تضمینی نیست که ایزوله بماند - کلادفلر هر وقت
// بخواهد دورش می‌ریزد - و همین خوب است: کش اینجا یک بهبود است، نه
// چیزی که درستیِ برنامه به آن وابسته باشد. اگر خالی باشد، همان کوئری
// اجرا می‌شود.
//
// ─── چیزی که عمداً کش نمی‌شود ────────────────────────────────────────
// هر چیزی که «حالِ لحظه‌ای» است: نشانگرِ ارسال، پرچمِ «امروز تمام شد»،
// وضعیت مشترک. دو ایزوله‌ی هم‌زمان با کشِ کهنه می‌توانند یک پیام را دو
// بار بفرستند. کش فقط برای داده‌ای است که خواندنش تکراری و تغییرش کند
// است.

const store = new Map();

/**
 * مقدار را از کش می‌دهد، یا اگر نبود می‌سازد و نگه می‌دارد.
 *
 * درخواست‌های هم‌زمان روی یک کلید به یک اجرا می‌رسند (single-flight):
 * بدون این، لحظه‌ای که کش منقضی می‌شود، ده‌ها درخواستِ هم‌زمان همگی
 * کوئری را می‌زنند - دقیقاً همان لحظه‌ای که بیشترین بار روی دیتابیس
 * است.
 *
 * @param {string} key
 * @param {number} ttlMs
 * @param {() => Promise<any>} loader
 */
export async function cached(key, ttlMs, loader) {
  const now = Date.now();
  const hit = store.get(key);

  // مقدارِ تازه.
  if (hit && hit.value !== undefined && hit.expires > now) {
    hits++;
    return hit.value;
  }

  // کسی همین حالا دارد می‌سازدش - به همان بپیوند. این هم برخورد است:
  // به دیتابیس نمی‌رسد.
  if (hit && hit.inflight) {
    hits++;
    return hit.inflight;
  }

  misses++;

  const inflight = (async () => {
    try {
      const value = await loader();
      store.set(key, { value, expires: Date.now() + ttlMs });
      return value;
    } catch (err) {
      // خطا کش نمی‌شود: یک قطعیِ گذرا نباید تا انقضای TTL تکرار شود.
      // ولی مقدارِ کهنه اگر هست می‌ماند تا دفعه‌ی بعد شانس دوباره باشد.
      store.delete(key);
      throw err;
    }
  })();

  store.set(key, { ...(hit || {}), inflight });
  return inflight;
}

/** کلیدهایی که با این پیشوند شروع می‌شوند را دور می‌ریزد. */
export function invalidate(prefix) {
  for (const key of store.keys()) {
    if (key.startsWith(prefix)) store.delete(key);
  }
}

/** فقط برای تست. */
export function clearAll() {
  store.clear();
  hits = 0;
  misses = 0;
}

export function size() {
  return store.size;
}

// شمارشِ برخورد و خطا، برای /admin/status.
//
// فقط مالِ همین ایزوله است و کلِ حساب را نمی‌گوید - ولی نسبتشان را
// می‌گوید، و وقتی کشی اضافه می‌کنی باید بتوانی ببینی واقعاً کار می‌کند
// یا نه. بدونِ این عدد، تنها راهِ فهمیدنِ مصرف، نگاه کردنِ دستی به
// داشبوردِ کلادفلر بود؛ و همان یعنی روزی که پر شود، از خودِ خرابی
// می‌فهمیم.
let hits = 0;
let misses = 0;

export function stats() {
  const total = hits + misses;
  return {
    keys: store.size,
    hits,
    misses,
    // درصدِ کوئری‌هایی که اصلاً به دیتابیس نرسیدند.
    hit_rate: total ? Math.round((hits / total) * 100) + "%" : "-",
  };
}
