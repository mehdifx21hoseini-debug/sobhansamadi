// چسباندنِ جهتِ متنِ فارسی به اطرافِ واژه‌های لاتین.
//
// ─── مشکل ──────────────────────────────────────────────────────────
//
// وقتی یک جمله‌ی فارسی واژه‌ی لاتین دارد («SSProX، Risk Free و Trail TP»)،
// تلگرام جهتِ علامت‌ها و فاصله‌های دورِ آن را از روی واژه‌ی لاتین
// می‌خواند و جمله به‌هم می‌ریزد: ویرگول جابه‌جا می‌شود، ترتیبِ واژه‌ها
// وسطِ جمله برعکس می‌افتد. ۱۲ اکتبر یک پاسخِ واقعیِ دستیار همین‌طور بود.
//
// راه‌حلِ استاندارد: یک نشانه‌ی نامرئیِ «راست‌به‌چپ» (RLM) دورِ هر تکه‌ی
// لاتین. نشانه دیده نمی‌شود، فقط جهتِ همسایه‌ها را فارسی نگه می‌دارد.
//
// آدرس‌ها دست نمی‌خورند: نویسه‌ی نامرئی وسطِ لینک آن را از کلیک‌پذیری
// می‌اندازد.

const RLM = "\u200f";
const URL_RE = /(https?:\/\/\S+)/g;
// یک تکه‌ی لاتین: حرف با رقم، و بینشان فاصله / نقطه / خط‌تیره / اسلش (مثل
// «Risk Free»، «Trail TP»، «MT5»، «InpRiskReward»، «2.1»).
const LATIN_RE = /[A-Za-z][A-Za-z0-9]*(?:[ .\-_/+]+[A-Za-z0-9]+)*/g;

export function fixBidi(text) {
  const s = String(text == null ? "" : text);
  if (!/[A-Za-z]/.test(s)) return s;
  return s
    .split(URL_RE)
    .map((part, i) => {
      if (i % 2 === 1) return part; // آدرس
      return part.replace(LATIN_RE, (m, offset, whole) => {
        const before = whole[offset - 1] === RLM ? "" : RLM;
        const after = whole[offset + m.length] === RLM ? "" : RLM;
        return before + m + after;
      });
    })
    .join("");
}
