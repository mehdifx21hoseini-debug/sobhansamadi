// نقشه‌ی خودِ ربات، برای دستیار هوشمند.
//
// ─── مسئله ─────────────────────────────────────────────────────────
//
// دستیار فقط از «پایگاه دانش» جواب می‌داد و پایگاه دانش درباره‌ی
// *موضوع‌ها*ست، نه درباره‌ی *ربات*. یعنی می‌دانست SSProX چیست و چه
// می‌کند، ولی نمی‌دانست کاربر برای گرفتنش باید کجا را بزند - و همان
// جمله‌ی «از دکمه SSProX در ربات» که در یک مدخل آمده، اسمِ دکمه را هم
// اشتباه می‌گفت: دکمه‌ای به نام SSProX در ربات نیست، اسمش «🤖 اکسپرت
// مدیریت سرمایه» است.
//
// نتیجه‌اش بدترین حالتِ ممکن بود: پاسخ درست به‌نظر می‌رسید و کاربر
// دنبال دکمه‌ای می‌گشت که وجود نداشت.
//
// ─── چرا اینجا و نه در پایگاه دانش ─────────────────────────────────
//
// دو دلیل، و هر دو مهم‌اند:
//
//   ۱. برچسب‌ها از خودِ منو import می‌شوند، نه دستی نوشته. هر بار که
//      اسم یک دکمه عوض شود، این نقشه خودش عوض می‌شود. مدخلِ دستی در
//      پایگاه دانش همان روز کهنه می‌شود و هیچ‌جا خطا نمی‌دهد.
//
//   ۲. پایگاه دانش با بازیابی می‌آید و فقط ۱۵ مدخلِ نزدیک به سوال به
//      مدل می‌رسد. نقشه‌ی راه باید *همیشه* آنجا باشد: کاربری که
//      می‌پرسد «اکسپرت مدیریت سرمایه رو از کجا بگیرم؟» ممکن است هیچ
//      مدخلی از دسته‌ی «مسیرها» را بالا نیاورد، و دقیقاً همان‌جا به
//      نقشه نیاز دارد.
//
// ─── مرزِ این فایل ─────────────────────────────────────────────────
//
// اینجا فقط «کجا را بزنم» است، نه «چیست». توضیحِ محتوا کارِ پایگاه
// دانش است و مدیر آن را از پنل عوض می‌کند؛ اگر شرحِ دوره‌ها هم اینجا
// می‌آمد، دو مرجع می‌شد که با هم می‌جنگند.
//
// و هیچ چیزِ مدیریتی اینجا نمی‌آید - دستور مدیر، پنل، مسیرهای مخفی.
// این متن به مدلی می‌رود که با کاربر حرف می‌زند.

