// پل بین «فرم پر شد» و «مکالمه با پشتیبانی».
//
// تا امروز کاربر بعد از تایید نهایی یک «ثبت شد» می‌دید و تمام. بعدش
// خودش باید آیدی پشتیبانی را از جایی پیدا می‌کرد، کپی می‌کرد، در
// جست‌وجوی تلگرام می‌چسباند و از صفر توضیح می‌داد که کیست و چه می‌خواهد.
// در همان فاصله بیشترشان می‌رفتند.
//
// اینجا هر سه قدم حذف می‌شود: یک دکمه که چت پشتیبانی را باز می‌کند، با
// پیامی که از قبل در کادر تایپ نشسته و کد پیگیری‌اش را هم دارد.
//
// چرا فقط «آماده» و نه «ارسال‌شده»: تلگرام به هیچ رباتی اجازه نمی‌دهد
// از طرف کاربر پیام بفرستد - و نباید هم بدهد. پارامتر text فقط کادر
// تایپ را پر می‌کند؛ ضربه‌ی آخر با خود کاربر است و پیام از اکانت خودش
// می‌رود، که همان چیزی است که پشتیبان لازم دارد.
//
// یک محدودیت که باید یادمان بماند: این پارامتر روی اکانت انسانی کار
// می‌کند نه روی ربات. آیدی پشتیبانی اگر روزی به یک ربات عوض شد، چت باز
// می‌شود ولی کادر خالی می‌ماند.

// آیدی از متغیر محیطی خوانده می‌شود تا عوض کردنش دیپلوی نخواهد -
// پشتیبانی چیزی است که ممکن است وسط یک روز شلوغ جابه‌جا شود.
const DEFAULT_SUPPORT = "sobhansforex";

/**
 * ایموجیِ ابتدای یک پاسخ را برمی‌دارد.
 *
 * متنِ دکمه‌های فرم ایموجی دارند («📗 مقدماتی - اصول را می‌دانم») و هر
 * جا که این پاسخ‌ها زیرِ یک برچسبِ ایموجی‌دار نوشته شوند، دو نشان پشتِ
 * سر هم می‌نشیند: «📊 دانش در مارکت: 📗 مقدماتی…». هیچ‌کدام چیزی اضافه
 * نمی‌کند و خط را شلوغ می‌کند.
 *
 * اینجا زندگی می‌کند و نه در فرم، چون هر دو جا - پیامِ آماده‌ی پشتیبانی
 * و رسیدِ خودِ ربات - به همین یک قاعده نیاز دارند.
 */
export function stripLeadingIcon(v) {
  return String(v === null || v === undefined ? "" : v)
    .trim()
    .replace(/^[^؀-ۿ0-9A-Za-z]+/, "");
}

export function supportUsername(env) {
  const raw = String((env && env.SUPPORT_USERNAME) || DEFAULT_SUPPORT).trim();
  return raw.replace(/^@/, "").replace(/^https?:\/\/t\.me\//i, "");
}

/**
 * کدام دوره را انتخاب کرده.
 *
 * از روی کلیدواژه تشخیص داده می‌شود نه با تساویِ رشته: نامِ دوره‌ها
 * ایموجی دارند و روزی ممکن است ایموجی یا نیم‌فاصله‌شان عوض شود. «هر دو»
 * اول بررسی می‌شود چون نامش نه «پیشرفته» دارد نه «روانشناسی».
 */
function courseKind(course) {
  const s = String(course || "");
  if (/هر دو/.test(s)) return "both";
  if (/روانشناسی|روان‌شناسی/.test(s)) return "psy";
  if (/پیشرفته/.test(s)) return "tech";
  return "";
}

/**
 * جمله‌ی اولِ هر مسیر - یک ساختار برای هر سه.
 *
 * پیشتر هرکدام لحنِ خودش را داشت و متنِ روانشناسی یک پاراگرافِ شعاری بود
 * («تا بتونم ذهن و عملکردم رو بهتر بشناسم و در مسیر تبدیل شدن به…»).
 * این پیام از طرفِ کاربر می‌رود و پشتیبان باید در دو ثانیه بفهمد طرف
 * کیست و چه می‌خواهد؛ جمله‌ی تبلیغاتی از زبانِ خودِ مشتری، هم غیرطبیعی
 * است هم خواندنش وقت می‌برد.
 */
const OPENERS = {
  tech: (name) => "من " + name + " هستم و فرم شرکت در «مجموعه آموزشی پیشرفته» را تکمیل کردم.",
  psy: (name) => "من " + name + " هستم و فرم شرکت در «دوره روانشناسی معامله‌گری» را تکمیل کردم.",
  both: (name) =>
    "من " + name +
    " هستم و فرم شرکت در «هر دو دوره» - مجموعه آموزشی پیشرفته و روانشناسی معامله‌گری - را تکمیل کردم.",
  "": (name) => "من " + name + " هستم و فرم مشاوره و ثبت‌نام را تکمیل کردم.",
};

// جمله‌ی آخر، یکی برای هر سه مسیر.
//
// «تعیین سطح» از آن برداشته شد: کاربر همین الان فرم را پر کرده و
// نوشتنِ دوباره‌اش چیزی اضافه نمی‌کند. به‌جایش یک درخواستِ مشخص آمده -
// «راهنمایی‌ام کنید» - نه فقط تشکر، تا پشتیبان بداند از او چه خواسته
// شده.
const CLOSER = "برای مشاوره پیام دادم؛ ممنون می‌شوم راهنمایی‌ام کنید.";

/**
 * متنی که در کادر تایپِ کاربر می‌نشیند - ساخته‌شده از همان چیزی که در
 * فرم نوشته.
 *
 * چرا پاسخ‌ها در خطِ برچسب‌دار می‌آیند نه وسطِ جمله: پاسخِ سطح و هدف
 * متنِ آزادند. «حدود {سطح} است که فعالیت می‌کنم» با پاسخِ «مبتدی هستم»
 * می‌شود «حدود مبتدی هستم است که فعالیت می‌کنم». خطِ برچسب‌دار هر پاسخی
 * را درست نشان می‌دهد - «۲ سال»، «مبتدی»، یا یک پاراگراف.
 *
 * خطِ خالی هم اصلاً نوشته نمی‌شود، نه با خط تیره: کسی که از دکمه‌ی
 * پایانِ دوره‌ی مقدماتی آمده ممکن است فقط نام و شماره داده باشد، و
 * «هدف: —» شبیهِ فرمِ ناقص است نه پیامِ آدم.
 *
 * کد پیگیری آخر می‌آید: پشتیبان با همان یک خط پرونده را در CRM پیدا
 * می‌کند، بدون اینکه نام و شماره را دوباره بپرسد - چیزی که کاربر دو
 * دقیقه پیش داده و پرسیدنِ دوباره‌اش بدترین شروعِ ممکن است.
 */
export function supportPrefill({
  leadId, name, course, level, experience, hasRealAccount, tradeStatus, goal,
} = {}) {
  const kind = courseKind(course);
  const who = String(name || "").trim();

  const lines = ["سلام، وقت بخیر 🌹", ""];
  lines.push(who ? OPENERS[kind](who) : "فرم مشاوره و ثبت‌نام را تکمیل کردم.");

  const clean = stripLeadingIcon;

  // خط‌های داده، بدونِ ایموجی و زیرِ یک سرخط.
  //
  // پیشتر هر خط ایموجیِ خودش را داشت (📊 ⏳ 💼 📈 🎯) و پیام شبیهِ یک
  // فرمِ رنگی می‌شد نه پیامی که یک آدم نوشته. تلگرام در کادرِ تایپ متنِ
  // ساده می‌گیرد و بولد ندارد، پس تاکید از ساختار می‌آید: یک سرخط که
  // می‌گوید این بخش داده است، و خط‌های برچسب‌دارِ پشتِ سرِ هم.
  const facts = [];
  if (clean(level)) facts.push("دانش من در مارکت: " + clean(level));
  if (clean(experience)) facts.push("مدت فعالیتم: " + clean(experience));
  if (clean(hasRealAccount)) {
    facts.push("حساب ریل: " + (clean(hasRealAccount) === "بله" ? "دارم" : "ندارم"));
  }
  if (clean(tradeStatus)) facts.push("وضعیت تریدم: " + clean(tradeStatus));
  if (clean(goal)) facts.push("هدفم از دوره: " + clean(goal));
  if (facts.length) lines.push("", "خلاصه‌ی پاسخ‌هایم:", ...facts);

  lines.push("", CLOSER);
  // کد پیگیری با یک خطِ خالی جدا می‌ماند تا انتخاب و کپی کردنش آسان
  // باشد - پشتیبان با همین یک خط پرونده را در CRM پیدا می‌کند.
  if (leadId) lines.push("", "کد پیگیری: " + leadId);
  return lines.join("\n");
}

/**
 * لینکِ چت با پشتیبانی، با پیام آماده.
 *
 * سقفِ آدرسِ دکمه در تلگرام بلند است ولی بی‌نهایت نیست؛ متنِ آماده کوتاه
 * می‌ماند و اگر روزی بلند شد، بریده می‌شود نه اینکه کل دکمه رد شود.
 */
export function supportChatUrl(env, prefill) {
  const base = "https://t.me/" + supportUsername(env);
  const text = String(prefill || "").slice(0, 600);
  return text ? base + "?text=" + encodeURIComponent(text) : base;
}
